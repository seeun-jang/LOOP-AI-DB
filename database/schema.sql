-- PostgreSQL 17. Fresh database migration; deliberately no DROP statements.
BEGIN;
CREATE TABLE users (
    user_id VARCHAR(50) PRIMARY KEY CHECK (user_id ~ '^[A-Za-z0-9_]{3,50}$'),
    password_hash VARCHAR(255) NOT NULL CHECK (length(password_hash) > 20),
    name VARCHAR(50) NOT NULL CHECK (length(btrim(name)) > 0),
    email VARCHAR(254) NOT NULL CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$')
);
CREATE TABLE topics (
    topic_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE CHECK (length(btrim(name)) > 0),
    description TEXT
);
CREATE TABLE sessions (
    session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(50) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    topic_id INTEGER NOT NULL REFERENCES topics(topic_id) ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'in_progress'
        CHECK (status IN ('in_progress', 'completed', 'stopped'))
);
CREATE TABLE messages (
    message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id INTEGER NOT NULL REFERENCES sessions(session_id) ON DELETE CASCADE,
    role VARCHAR(10) NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL CHECK (length(btrim(content)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE questions (
    question_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id INTEGER NOT NULL REFERENCES sessions(session_id) ON DELETE CASCADE,
    content TEXT NOT NULL CHECK (length(btrim(content)) > 0),
    answer TEXT NOT NULL CHECK (length(btrim(answer)) > 0),
    explanation TEXT
);
CREATE TABLE attempts (
    attempt_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id INTEGER NOT NULL REFERENCES questions(question_id) ON DELETE CASCADE,
    submitted_answer TEXT NOT NULL CHECK (length(btrim(submitted_answer)) > 0),
    is_correct BOOLEAN,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ai_feedback TEXT
);
CREATE TABLE prompt_experiments (
    experiment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(50) NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    question TEXT NOT NULL CHECK (length(btrim(question)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE experiment_results (
    result_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id INTEGER NOT NULL REFERENCES prompt_experiments(experiment_id) ON DELETE CASCADE,
    variant CHAR(1) NOT NULL CHECK (variant IN ('A', 'B')),
    prompt TEXT NOT NULL CHECK (length(btrim(prompt)) > 0),
    response TEXT NOT NULL CHECK (length(btrim(response)) > 0),
    UNIQUE (experiment_id, variant)
);
-- Index all FK lookup paths used by ownership, history, cascade and statistics.
CREATE INDEX idx_sessions_user ON sessions(user_id, started_at DESC, session_id DESC);
CREATE INDEX idx_sessions_topic ON sessions(topic_id);
CREATE INDEX idx_messages_session ON messages(session_id, message_id);
CREATE INDEX idx_questions_session ON questions(session_id, question_id);
CREATE INDEX idx_attempts_question ON attempts(question_id, attempt_id);
CREATE INDEX idx_experiments_user ON prompt_experiments(user_id, experiment_id DESC);
COMMIT;
